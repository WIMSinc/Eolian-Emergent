/**
 * Generate narrow WebP variants for the card images in public/, and write the
 * manifest that lib/responsiveImage.js builds srcset from.
 *
 *   node scripts/generate-image-variants.mjs
 *
 * Re-run after adding or replacing any image listed in SOURCES, then commit
 * both the new files and the regenerated manifest.
 *
 * Two rules this encodes:
 *
 * 1. Variants are new files, never re-encodes in place. Everything under
 *    public/*.webp is served `immutable, max-age=31536000`, so overwriting a
 *    file strands returning visitors on the stale copy for up to a year
 *    (CLAUDE.md §6.3). A new width means a new name.
 *
 * 2. The original is the largest srcset candidate rather than a regenerated
 *    copy of itself. Re-encoding the 800px originals produced files the same
 *    size — they were already at the quality floor — so a duplicate would add
 *    files and cache entries for nothing.
 *
 * The manifest exists so srcset only ever advertises widths that were actually
 * written. Advertising a width whose file does not exist is a 404 the browser
 * hides by falling back, which is exactly the kind of failure nobody notices.
 */

import sharp from "sharp";
import { readFileSync, writeFileSync, existsSync, statSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const PUBLIC = join(root, "public");

// Every image rendered inside a responsive card grid. Hero art, the logo and
// og: images are deliberately absent: they are either sized correctly already
// or on the critical path, where a change costs more than the bytes save.
const SOURCES = [
  "/artak-overview.webp",
  "/artak-mission-planning.webp",
  "/artak-roc-drill.webp",
  "/artak-c2.webp",
  "/artak-in-action-thumb.webp",
  "/artak-c2-thumb.webp",
  "/artak-xr-sdve-thumb.webp",
];

const CANDIDATE_WIDTHS = [400, 600, 800, 1200];
const QUALITY = 74;

const kb = (n) => (n / 1024).toFixed(1);

const manifest = {};
let generated = 0;

for (const src of SOURCES) {
  const file = join(PUBLIC, src);
  if (!existsSync(file)) {
    console.error(`  MISSING  ${src} — skipped`);
    continue;
  }

  const { width: intrinsic } = await sharp(file).metadata();
  const base = src.slice(0, -".webp".length);
  // Only widths genuinely narrower than the source; upscaling would add bytes
  // to no benefit and lie about the resolution on offer.
  const widths = CANDIDATE_WIDTHS.filter((w) => w < intrinsic);

  for (const w of widths) {
    const out = join(PUBLIC, `${base}-${w}.webp`);
    await sharp(file)
      .resize({ width: w, withoutEnlargement: true })
      .webp({ quality: QUALITY, effort: 6 })
      .toFile(out);
    generated += 1;
    console.log(`  ${`${base}-${w}.webp`.padEnd(40)} ${kb(statSync(out).size)} KB`);
  }

  manifest[src] = { widths, intrinsic };
  console.log(
    `  -> ${src} original ${intrinsic}w ${kb(statSync(file).size)} KB\n`,
  );
}

const out = join(root, "lib", "imageVariants.js");
writeFileSync(
  out,
  `// GENERATED by scripts/generate-image-variants.mjs — do not edit by hand.\n` +
    `// Maps each source image to the narrower variants written beside it.\n` +
    `export const IMAGE_VARIANTS = ${JSON.stringify(manifest, null, 2)};\n`,
);

console.log(`  wrote lib/imageVariants.js — ${generated} variants, ${Object.keys(manifest).length} sources`);
